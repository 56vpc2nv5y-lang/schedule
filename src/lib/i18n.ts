type DeepStringify<T> = {
  [K in keyof T]: T[K] extends (...args: infer A) => string
    ? (...args: A) => string
    : T[K] extends string
      ? string
      : T[K] extends readonly string[]
        ? readonly string[]
        : DeepStringify<T[K]>;
};

export type Dict = DeepStringify<typeof zh>;

